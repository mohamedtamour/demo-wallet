// Arabic / English for every UI string. The backend translates its own texts (service names, field labels,
// assistant replies) from the X-Lang header that transport.js sends with every request.

const KEY = 'lang';
let current = (() => {
  try { const v = localStorage.getItem(KEY); if (v === 'en' || v === 'ar') return v; } catch { /* storage unavailable */ }
  return 'ar'; // Arabic first; one tap switches to English
})();

export const lang = () => current;
export const isEn = () => current === 'en';

export function applyDir() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'en' ? 'ltr' : 'rtl';
}

// Run fn with t() / isEn() answering in another language, without touching the app language (used for the
// assistant chat, which replies in the language of each message while the app keeps the one the user picked).
export function withLang(l, fn) {
  const prev = current;
  if (l === 'en' || l === 'ar') current = l;
  try { return fn(); } finally { current = prev; }
}

export function setLang(l) {
  current = l === 'en' ? 'en' : 'ar';
  try { localStorage.setItem(KEY, current); } catch { /* storage unavailable */ }
  applyDir();
}

